export function listPhysicians(): Physician[] {
  return PHYSICIAN_GROUPS.flatMap((group) =>
    group.names.map((name, index) => ({
      id: `${group.id}-${index + 1}`,
      name,
      specialty: group.label,
      specialtyId: group.id,
    })),
  );
}

export function getPhysician(id: string | undefined | null): Physician | null {
  if (!id) return null;
  return listPhysicians().find((physician) => physician.id === id) ?? null;
}
